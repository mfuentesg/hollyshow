#!/usr/bin/env node
// Regenerates packages/protocol/src/generated from the Rust types (ts-rs).
//
// Ownership rule (docs/ARCHITECTURE.md): only `hollyshow-core` defines exported wire types.
// Every other crate references them. The export tests are still run workspace-wide so a type
// accidentally exported elsewhere is picked up (and shows in the CI drift check) instead of
// silently missing.
//
// Safety: output goes to a temp dir first and is swapped in only after cargo succeeded, so an
// aborted run never leaves `generated/` empty. The barrel (index.ts) is produced here.
import { execFileSync } from "node:child_process";
import { chmodSync, mkdtempSync, readdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "packages/protocol/src/generated");
const tmp = mkdtempSync(join(tmpdir(), "hollyshow-ts-"));

try {
  execFileSync("cargo", ["test", "--workspace", "--quiet", "export_bindings"], {
    cwd: root,
    stdio: "inherit",
    env: { ...process.env, TS_RS_EXPORT_DIR: tmp },
  });

  const names = readdirSync(tmp)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .map((f) => f.slice(0, -3))
    .sort();
  if (names.length === 0) throw new Error("ts-rs exported nothing; refusing to replace generated/");
  const barrel =
    "// Generated by scripts/gen-types.mjs. Do not edit.\n" +
    names.map((n) => `export type { ${n} } from "./${n}";`).join("\n") +
    "\n";
  writeFileSync(join(tmp, "index.ts"), barrel);

  chmodSync(tmp, 0o755);
  rmSync(out, { recursive: true, force: true });
  try {
    renameSync(tmp, out);
  } catch {
    // Cross-device rename (tmp on another filesystem): copy then remove.
    execFileSync("node", [
      "-e",
      `require("fs").cpSync(${JSON.stringify(tmp)}, ${JSON.stringify(out)}, {recursive:true})`,
    ]);
    rmSync(tmp, { recursive: true, force: true });
  }
  console.log(`generated ${names.length} types in ${out}`);
} catch (e) {
  rmSync(tmp, { recursive: true, force: true });
  console.error(String(e));
  process.exit(1);
}
