#!/usr/bin/env node
// Regenerates packages/protocol/src/generated from the Rust types (ts-rs) and rewrites the barrel.
// `.cargo/config.toml` points TS_RS_EXPORT_DIR at the output directory.
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "packages/protocol/src/generated");

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

execFileSync("cargo", ["test", "-p", "hollyshow-core", "--quiet", "export_bindings"], {
  cwd: root,
  stdio: "inherit",
});

const names = readdirSync(out)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .map((f) => f.slice(0, -3))
  .sort();
const barrel =
  "// Generated by scripts/gen-types.mjs. Do not edit.\n" +
  names.map((n) => `export type { ${n} } from "./${n}";`).join("\n") +
  "\n";
writeFileSync(join(out, "index.ts"), barrel);
console.log(`generated ${names.length} types in ${out}`);
